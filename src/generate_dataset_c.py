"""Create a synthetic low-Fatal-prevalence stress-test sample from Dataset B.

Dataset C is selected without replacement from the independently generated B
sample. It preserves the existing feature/label pairs and changes only the
class prior. It is therefore a prior-shift stress test, not a new independent
dataset or real-world validation set.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "synthetic_dataset_B_5000.csv"
DESTINATION = ROOT / "data" / "synthetic_dataset_C_prior_shift_2000.csv"
METADATA = ROOT / "data" / "dataset_C_metadata.json"
TARGET_COUNTS = {"Slight": 1500, "Serious": 470, "Fatal": 30}
SEED = 2027


def main() -> None:
    source = pd.read_csv(SOURCE)
    pieces = []
    for label, count in TARGET_COUNTS.items():
        candidates = source.loc[source["severity"].eq(label)]
        if count > len(candidates):
            raise ValueError(
                f"Dataset B has only {len(candidates)} {label} rows; "
                f"cannot select {count} rows without replacement."
            )
        pieces.append(candidates.sample(n=count, replace=False, random_state=SEED + len(pieces)))

    dataset_c = (
        pd.concat(pieces, ignore_index=True)
        .sample(frac=1, random_state=SEED)
        .reset_index(drop=True)
    )
    dataset_c.to_csv(DESTINATION, index=False)
    metadata = {
        "dataset": "C",
        "purpose": "synthetic class-prior-shift stress test",
        "source": "Dataset B, independently generated by the same declared simulator",
        "selection": "class-conditional sampling without replacement; labels and feature rows are unchanged",
        "rows": len(dataset_c),
        "seed": SEED,
        "target_counts": TARGET_COUNTS,
        "observed_counts": dataset_c["severity"].value_counts().reindex(TARGET_COUNTS, fill_value=0).to_dict(),
        "observed_proportions": dataset_c["severity"].value_counts(normalize=True).reindex(TARGET_COUNTS, fill_value=0).to_dict(),
        "limitations": [
            "Dataset C is a subset of Dataset B, so their evaluation results are not independent replications.",
            "The class prior is an assumed STATS19-inspired scenario; all features and labels remain synthetic.",
            "No repeated rows are added, but records in C are also present in B by design.",
            "This dataset cannot establish real-world performance or calibrated real-world probabilities.",
        ],
    }
    METADATA.write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"Wrote {len(dataset_c):,} rows to {DESTINATION}")
    print(dataset_c["severity"].value_counts().reindex(TARGET_COUNTS))


if __name__ == "__main__":
    main()
